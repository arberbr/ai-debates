import { IsString, IsNumber, Min, Max, Length, IsOptional } from 'class-validator';

export class StartDebateDto {
  @IsString()
  @Length(1, 300)
  topic: string;

  @IsString()
  @Length(1, 100)
  yesModel: string;

  @IsString()
  @Length(1, 100)
  noModel: string;

  @IsNumber()
  @Min(1)
  @Max(5)
  rounds: number;

  @IsString()
  @IsOptional()
  @Length(0, 2000)
  judgePrompt?: string;

  @IsString()
  @IsOptional()
  @Length(1, 200)
  title?: string; // Optional: title already generated by frontend

  @IsString()
  @IsOptional()
  api_key?: string;
}
